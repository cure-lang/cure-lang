defmodule Cure.Test.ProofRecipeFixture do
  @moduledoc false

  alias Cure.Core.{Env, Inductive, ProofRecipe, Term}
  alias Cure.Test.ProofSnapshotFixture

  def table, do: ["", "Boundary#Packed", "Boundary#Pack", "Boundary#Alternate", "payload"]

  # Explicit annotations for ONE fixture, not a certificate inference pass.
  # Asserted conversion terms are built from its actual source declarations.
  def certificate do
    env = ProofSnapshotFixture.environment()
    %{body: {:case, value, motive, _branches}} = Env.get_def(env, :"Boundary#unpack")
    pack = Inductive.get_ctor(env, :"Boundary#Pack")
    alternate = Inductive.get_ctor(env, :"Boundary#Alternate")
    constructor = {:r_ctor, [], [], [:r_leaf, :r_leaf]}
    data = {:r_data, [], [:r_leaf]}
    kind = {:r_pi, :r_leaf, {:r_pi, data, :r_leaf}}
    motive_recipe = {:r_lam, :r_leaf, {:r_lam, data, :r_leaf}}
    [alternate_index] = alternate.result_indices

    branches = [
      branch(pack, motive, :c_beta),
      branch(alternate, motive, {:c_trans, alternate_index, :c_beta, :c_beta})
    ]

    case_recipe = {:r_case, constructor, [], [:r_leaf], 0, kind, motive_recipe, branches}
    middle = {:app, beta({:app, motive, {:atom_type}}), value}
    conversion = {:c_trans, middle, {:c_app, :c_beta, :c_refl}, :c_beta}
    scalar = {:packet, :r_leaf, :r_leaf}
    packed = {:packet, data, constructor}
    unpack = {:packet, :r_leaf, {:r_convert, {:atom_type}, conversion, case_recipe}}
    pack_recipe = {:constructor_recipe, [], [:r_leaf, :r_leaf], [], [:r_leaf]}

    alternate_recipe =
      {:constructor_recipe, [], [:r_leaf, :r_leaf], [], [{:r_app, {:r_lam, :r_leaf, :r_leaf}, :r_leaf}]}

    families = [{:family_recipe, [], [:r_leaf], [pack_recipe, alternate_recipe]}]
    {:certificate, families, [scalar, scalar, packed, unpack]}
  end

  def to_agda do
    with {:ok, characters} <- ProofRecipe.encode_certificate(certificate(), table()) do
      names = Enum.map_join(table(), " ∷ ", &inspect/1) <> " ∷ []"

      {:ok,
       """
       -- Generated by proof/scripts/generate-wire-certificate.exs.
       -- Literal producer output; independently checked, not extraction refinement.
       module Fixtures.ExecutableCertificate where
       open import Data.Char using (Char)
       open import Data.List using (List; []; _∷_)
       open import Data.String.Base using (toList)
       open import Core.Syntax using (Name)

       table : List Name
       table = #{names}
       characters : List Char
       characters = toList "#{characters}"
       """}
    end
  end

  defp branch(ctor, motive, tail) do
    # This fixture has no parameters and exactly two surface fields.
    [_, _] = ctor.args
    [index] = ctor.result_indices
    value = {:ctor, ctor.name, [{:var, 1}, {:var, 0}]}
    goal = {:app, {:app, Term.shift(motive, 2, 0), index}, value}
    middle = {:app, beta({:app, Term.shift(motive, 2, 0), index}), value}
    conversion = {:c_sym, {:c_trans, middle, {:c_app, :c_beta, :c_refl}, tail}}
    {[:r_leaf, :r_leaf], {:r_convert, goal, conversion, :r_leaf}}
  end

  defp beta({:app, {:lam, _grade, _domain, body}, argument}),
    do: body |> Term.subst(0, Term.shift(argument, 1, 0)) |> Term.shift(-1, 0)
end
