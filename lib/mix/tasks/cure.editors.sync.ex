defmodule Mix.Tasks.Cure.Editors.Sync do
  @moduledoc """
  Regenerate the keyword lists the editor integrations share, and check that
  the parts this task cannot write are in step with them.

      mix cure.editors.sync           # rewrite the generated files
      mix cure.editors.sync --check   # fail when anything is out of date

  The vocabulary comes from the compiler, not from a hand-kept list:

    * keywords and contextual keywords from `Cure.Compiler.Lexer`;
    * declaration heads ("containers") from the standard-library macros that
      take a module name (`macro app <name: ModuleName>`), plus `proof`;
    * the macro-entry vocabulary (`syntax family`, `accepts`, `expands with`,
      ...) from `@macro_vocabulary` below, each word of which must still be
      matched by `Cure.Compiler.Parser`.

  Written by this task:

    * `tree-sitter-cure/keywords.js`
    * the generated block in `neovim-cure/syntax/cure.vim`
    * the generated block in `highlightjs-cure/src/languages/cure.js`
    * `highlightjs-cure/dist/cure.min.js`, built from the source above

  Checked only, with the command that fixes them:

    * `tree-sitter-cure/src/` (regenerated with the tree-sitter CLI)
    * `vscode-cure/syntaxes/cure.tmLanguage.json` (`npm run build-grammar`;
      checked exactly when `node` is on PATH)
    * the copies of the tree-sitter queries in `zed-cure` and `neovim-cure`
    * every contextual keyword and macro word is handled by the tree-sitter
      queries, the TextMate grammar, the Vim syntax file and highlight.js
    * the language server's semantic tokens know the same containers and
      every contextual keyword
  """

  use Mix.Task

  alias Cure.Compiler.Lexer

  @shortdoc "Regenerate the editor keyword lists from the lexer and stdlib"

  @literals ~w(true false nil)
  @word_operators ~w(and or not band bor bxor bsl bsr bnot)

  # Words that open or link macro entries. The parser matches them as
  # identifiers, so the lexer has no list of them.
  @macro_vocabulary ~w(
    syntax family accepts expands with computed directly by literal example explain
    fail open includes optional repeated one_or_more keyword becomes
    contextual is because
  )

  @begin_marker "BEGIN generated by mix cure.editors.sync"
  @end_marker "END generated by mix cure.editors.sync"

  @keywords_js "tree-sitter-cure/keywords.js"
  @grammar_json "tree-sitter-cure/src/grammar.json"
  @queries "tree-sitter-cure/queries"
  @vim_syntax "neovim-cure/syntax/cure.vim"
  @hljs_src "highlightjs-cure/src/languages/cure.js"
  @hljs_dist "highlightjs-cure/dist/cure.min.js"
  @tm_language "vscode-cure/syntaxes/cure.tmLanguage.json"
  @tm_builder "vscode-cure/scripts/build-grammar.js"
  @query_copies [
    {"highlights.scm", "zed-cure/languages/cure/highlights.scm"},
    {"brackets.scm", "zed-cure/languages/cure/brackets.scm"},
    {"outline.scm", "zed-cure/languages/cure/outline.scm"},
    {"highlights.scm", "neovim-cure/queries/cure/highlights.scm"}
  ]

  @impl Mix.Task
  def run(args) do
    {opts, _} = OptionParser.parse!(args, strict: [check: :boolean])
    Mix.Task.run("compile")
    root = File.cwd!()

    if !opts[:check], do: write_generated(root)

    case check(root) do
      [] ->
        Mix.shell().info("editor grammars are in sync")

      problems ->
        Enum.each(problems, &Mix.shell().error("  * " <> &1))
        Mix.raise("editor grammars are out of date (#{length(problems)} problem(s))")
    end
  end

  defp write_generated(root) do
    for {path, content} <- generated(root), read(root, path) != content do
      File.write!(Path.join(root, path), content)
      Mix.shell().info("wrote #{path}")
    end
  end

  @doc "The shared vocabulary, derived from the compiler and the stdlib."
  @spec vocabulary(Path.t()) :: %{atom() => [String.t()]}
  def vocabulary(root \\ File.cwd!()) do
    contextual = Enum.map(Lexer.contextual_keywords(), &Atom.to_string/1)

    keywords =
      Lexer.keywords()
      |> Enum.map(&Atom.to_string/1)
      |> Enum.reject(&(&1 in contextual or &1 in @literals))

    %{
      keywords: keywords,
      word_operators: Enum.filter(keywords, &(&1 in @word_operators)),
      contextual: contextual,
      containers: containers(root),
      macro_vocabulary: @macro_vocabulary
    }
  end

  # `macro app <name: ModuleName>` in lib/std declares the `app` container.
  defp containers(root) do
    Path.wildcard(Path.join(root, "lib/std/**/*.cure"))
    |> Enum.flat_map(fn file ->
      Regex.scan(~r/^\s*macro ([a-z_]+) <\w+: ModuleName>/m, File.read!(file), capture: :all_but_first)
    end)
    |> List.flatten()
    |> Enum.uniq()
    |> Enum.sort()
    |> Kernel.++(["proof"])
  end

  @doc "The files this task writes, as `{relative_path, content}`."
  @spec generated(Path.t()) :: [{Path.t(), String.t()}]
  def generated(root \\ File.cwd!()) do
    vocab = vocabulary(root)
    hljs_src = replace_block(read(root, @hljs_src), "  // ", hljs_block(vocab))

    [
      {@keywords_js, keywords_js(vocab)},
      {@vim_syntax, replace_block(read(root, @vim_syntax), "\" ", vim_block(vocab))},
      {@hljs_src, hljs_src},
      {@hljs_dist, hljs_dist(hljs_src)}
    ]
  end

  @doc "Everything that is out of date, as messages; empty when in sync."
  @spec check(Path.t()) :: [String.t()]
  def check(root \\ File.cwd!()) do
    vocab = vocabulary(root)

    stale =
      for {path, content} <- generated(root), read(root, path) != content do
        "#{path} is out of date; run `mix cure.editors.sync`"
      end

    stale ++
      check_parser_vocabulary(root) ++
      check_tree_sitter(root, vocab) ++
      check_tm_language(root, vocab) ++
      check_query_copies(root) ++
      check_positional_words(root, vocab) ++
      check_semantic_tokens(vocab)
  end

  defp check_parser_vocabulary(root) do
    parser = read(root, "lib/cure/compiler/parser.ex")

    for word <- @macro_vocabulary,
        not String.contains?(parser, ~s("#{word}")) and not Regex.match?(~r/:#{word}\b/, parser) do
      "`#{word}` is in @macro_vocabulary (#{__MODULE__}) but Cure.Compiler.Parser no longer matches it"
    end
  end

  defp check_tree_sitter(root, vocab) do
    rules = root |> read(@grammar_json) |> JSON.decode!() |> Map.fetch!("rules")
    fix = "regenerate it: cd tree-sitter-cure && npx tree-sitter-cli generate"

    [
      {"keyword", vocab.keywords},
      {"container_declaration", vocab.containers}
    ]
    |> Enum.flat_map(fn {rule, expected} ->
      found = rules |> Map.fetch!(rule) |> strings()

      if MapSet.new(found) == MapSet.new(expected),
        do: [],
        else: ["#{@grammar_json}: rule `#{rule}` does not match keywords.js; #{fix}"]
    end)
  end

  defp check_tm_language(root, vocab) do
    exact =
      case System.find_executable("node") do
        nil ->
          []

        node ->
          case System.cmd(node, [Path.join(root, @tm_builder), "--check"], cd: root, stderr_to_stdout: true) do
            {_, 0} -> []
            {_, _} -> ["#{@tm_language} is out of date; run `npm run build-grammar` in vscode-cure"]
          end
      end

    grammar = read(root, @tm_language)
    words = vocab.keywords ++ vocab.containers

    missing =
      for word <- words, not Regex.match?(~r/[|(:]#{word}[|)]/, grammar), do: word

    exact ++
      if missing == [],
        do: [],
        else: ["#{@tm_language} lacks #{Enum.join(missing, ", ")}; run `npm run build-grammar` in vscode-cure"]
  end

  defp check_query_copies(root) do
    for {source, copy} <- @query_copies, read(root, Path.join(@queries, source)) != read(root, copy) do
      "#{copy} differs from #{@queries}/#{source}; copy it over"
    end
  end

  # Contextual keywords and macro words are keywords only in some positions,
  # so each editor matches them with hand-written rules. Check none is lost.
  defp check_positional_words(root, vocab) do
    words = vocab.contextual ++ vocab.macro_vocabulary

    [
      {Path.join(@queries, "highlights.scm"), fn text, w -> String.contains?(text, ~s("#{w}")) end},
      {@tm_language, &word_in?/2},
      {@vim_syntax, &word_in?/2},
      {@hljs_src, &word_in?/2}
    ]
    |> Enum.flat_map(fn {path, present?} ->
      text = read(root, path)

      case Enum.reject(words, &present?.(text, &1)) do
        [] -> []
        missing -> ["#{path} has no rule for #{Enum.join(missing, ", ")}"]
      end
    end)
  end

  # The language server marks contextual words as keywords from its own lists.
  defp check_semantic_tokens(vocab) do
    semantic = Cure.LSP.Server.semantic_vocabulary()
    where = "Cure.LSP.Server's semantic-token vocabulary"

    containers =
      if MapSet.new(semantic.containers) == MapSet.new(vocab.containers),
        do: [],
        else: ["#{where} lists containers #{inspect(semantic.containers)}, expected #{inspect(vocab.containers)}"]

    containers ++
      case vocab.contextual -- semantic.words do
        [] -> []
        missing -> ["#{where} has no rule for #{Enum.join(missing, ", ")}"]
      end
  end

  # A word, possibly right after a regex word boundary (`\b`, `\<`, `\zs`).
  defp word_in?(text, word), do: Regex.match?(~r/(?:^|[^a-z_]|\\b|\\zs)#{word}(?![a-z_])/m, text)

  defp strings(%{"type" => "STRING", "value" => value}), do: [value]
  defp strings(map) when is_map(map), do: map |> Map.values() |> Enum.flat_map(&strings/1)
  defp strings(list) when is_list(list), do: Enum.flat_map(list, &strings/1)
  defp strings(_), do: []

  # -- Generated content ------------------------------------------------------

  defp keywords_js(vocab) do
    """
    // Generated by `mix cure.editors.sync`; do not edit. Shared by grammar.js
    // and the editor grammars built from it (vscode-cure/scripts/build-grammar.js).

    // Reserved words (`@keywords` in lib/cure/compiler/lexer.ex), minus the
    // contextual ones and the literals `true`, `false` and `nil`.
    const KEYWORDS = #{js_array(vocab.keywords)};

    // The keywords that are word operators.
    const WORD_OPERATORS = #{js_array(vocab.word_operators)};

    // Identifiers the parser promotes to keywords in context
    // (`@contextual_keywords` in the lexer).
    const CONTEXTUAL_KEYWORDS = #{js_array(vocab.contextual)};

    // Declaration heads: the stdlib macros that take a module name
    // (`macro app <name: ModuleName>`), plus `proof`. Identifiers lexically,
    // keywords only when they head a declaration (`fsm Turnstile`).
    const CONTAINERS = #{js_array(vocab.containers)};

    // Words that open or link macro entries (`syntax family`, `accepts`,
    // `expands with`, ...). Identifiers lexically.
    const MACRO_VOCABULARY = #{js_array(vocab.macro_vocabulary)};

    module.exports = {
      KEYWORDS,
      WORD_OPERATORS,
      CONTEXTUAL_KEYWORDS,
      CONTAINERS,
      MACRO_VOCABULARY,
    };
    """
  end

  defp js_array(words) do
    lines =
      words
      |> Enum.map(&"'#{&1}'")
      |> Enum.chunk_while(
        [],
        fn word, line ->
          if line != [] and String.length(Enum.join(Enum.reverse([word | line]), ", ")) > 74,
            do: {:cont, Enum.join(Enum.reverse(line), ", "), [word]},
            else: {:cont, [word | line]}
        end,
        fn line -> {:cont, Enum.join(Enum.reverse(line), ", "), []} end
      )

    "[\n" <> Enum.map_join(lines, "", &"  #{&1},\n") <> "]"
  end

  defp vim_block(vocab) do
    control = vocab.keywords -- vocab.word_operators

    """
    syn keyword cureKeyword #{Enum.join(control, " ")}
    syn keyword cureOperatorWord #{Enum.join(vocab.word_operators, " ")}
    syn keyword cureBoolean true false
    syn keyword cureNil nil
    syn match cureContainer "\\<\\(#{Enum.join(vocab.containers, "\\|")}\\)\\ze\\s\\+\\u"
    """
  end

  defp hljs_block(vocab) do
    """
    const CURE_KEYWORDS = #{js_array(vocab.keywords -- vocab.word_operators)};
    const WORD_OPERATORS = #{js_array(vocab.word_operators)};
    const CONTAINERS = #{js_array(vocab.containers)};
    """
  end

  defp hljs_dist(src) do
    [_header, body] = String.split(src, "export default ", parts: 2)

    """
    /*! `cure` grammar for Highlight.js 11.x. Generated from
        src/languages/cure.js by `mix cure.editors.sync`; do not edit. */
    (() => {
      "use strict";
      const cure = #{String.trim_trailing(body)};

      // Register with the global highlight.js instance when available so the
      // grammar is usable by a plain `<script src="cure.min.js"></script>`
      // inclusion after `highlight.min.js`.
      if (typeof hljs !== "undefined" && typeof hljs.registerLanguage === "function") {
        hljs.registerLanguage("cure", cure);
      } else if (typeof module !== "undefined" && module.exports) {
        module.exports = cure;
      } else if (typeof define === "function" && define.amd) {
        define(() => cure);
      }
    })();
    """
  end

  # Replaces the lines between the BEGIN/END markers (comment prefix `prefix`).
  defp replace_block(text, prefix, block) do
    begin_line = prefix <> @begin_marker
    end_line = prefix <> @end_marker

    case String.split(text, [begin_line <> "\n", end_line <> "\n"]) do
      [before, _old, rest] ->
        indent = String.replace(prefix, ~r/\S.*$/, "")

        body =
          block
          |> String.split("\n", trim: true)
          |> Enum.map_join("", &(indent <> &1 <> "\n"))

        before <> begin_line <> "\n" <> body <> end_line <> "\n" <> rest

      _ ->
        Mix.raise("missing `#{String.trim(begin_line)}` ... `#{String.trim(end_line)}` block")
    end
  end

  defp read(root, path), do: File.read!(Path.join(root, path))
end
